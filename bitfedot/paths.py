"""Filesystem layout. Everything lives in the user's home; nothing is written
outside it. Set BITFEDOT_ROOT to relocate the whole tree (used by tests)."""
import os
from pathlib import Path

APP_ID = "io.github.g0sha256.BitFedot"
APP_NAME = "BitFedot"

PKG_DIR = Path(__file__).resolve().parent
KEYS_DIR = PKG_DIR / "keys"
ASSETS_DIR = PKG_DIR / "data"

_root = os.environ.get("BITFEDOT_ROOT")
if _root:
    _r = Path(_root)
    CONFIG_DIR = _r / "config" / "bitfedot"
    DATA_DIR = _r / "share" / "bitfedot"
    UNIT_DIR = _r / "systemd-user"
    QUADLET_DIR = _r / "quadlet"
    AUTOSTART_DIR = _r / "autostart"
else:
    _cfg = Path(os.environ.get("XDG_CONFIG_HOME") or Path.home() / ".config")
    _data = Path(os.environ.get("XDG_DATA_HOME") or Path.home() / ".local/share")
    CONFIG_DIR = _cfg / "bitfedot"
    DATA_DIR = _data / "bitfedot"
    UNIT_DIR = _cfg / "systemd/user"
    QUADLET_DIR = _cfg / "containers/systemd"
    AUTOSTART_DIR = _cfg / "autostart"

# Home directory, for the configuration of optional apps (e.g. ~/.sparrow).
HOME = (Path(_root) / "home") if _root else Path.home()

SETTINGS_FILE = CONFIG_DIR / "settings.json"

# The project was called "Nodestead" before its first public release; migrate.py
# adopts an install made under that name.
LEGACY_NAME = "nodestead"
LEGACY_APP_ID = "io.github.nodestead.Nodestead"
OLD_APP_IDS = (LEGACY_APP_ID, "io.github.bitfedot.BitFedot")   # desktop/autostart files to clean up
LEGACY_CONFIG_DIR = CONFIG_DIR.with_name(LEGACY_NAME)
LEGACY_DATA_DIR = DATA_DIR.with_name(LEGACY_NAME)
APPS_DIR = DATA_DIR / "apps"            # apps/<name>/<version>, apps/<name>/current -> version
DOWNLOADS_DIR = DATA_DIR / "downloads"
COMPAT_LIB_DIR = DATA_DIR / "compat-lib"  # sonames upstream binaries expect but Fedora names differently
DEFAULT_CHAIN_DIR = DATA_DIR / "chain"  # bulk data (blocks, indexes); user may relocate

BITCOIN_CONF = CONFIG_DIR / "bitcoin.conf"
FULCRUM_CONF = CONFIG_DIR / "fulcrum.conf"
TOR_DIR = DATA_DIR / "tor"
TORRC = CONFIG_DIR / "torrc"
APPLY_LOCK = CONFIG_DIR / ".apply.lock"      # held while services are being reconfigured
ACTIVITY_FILE = CONFIG_DIR / ".activity"     # what that reconfiguration is doing right now
DESKTOP_DIR = (Path(_root) / "applications") if _root else _data / "applications"
MEMPOOL_DIR = DATA_DIR / "mempool"

# systemd --user units
U_BITCOIND = "bitfedot-bitcoind.service"
U_TOR = "bitfedot-tor.service"
U_FULCRUM = "bitfedot-fulcrum.service"
U_AGENT = "bitfedot-agent.service"
U_MEMPOOL = "bitfedot-mempool-pod.service"          # generated by Quadlet
U_MEMPOOL_PARTS = ("bitfedot-mempool-db.service", "bitfedot-mempool-api.service",
                   "bitfedot-mempool-web.service")

# Local ports (all bound to 127.0.0.1 unless inbound clearnet is enabled)
RPC_PORT = 8332
P2P_PORT = 8333
ONION_P2P_PORT = 8334
ZMQ_PORT = 28332
TOR_SOCKS = 9250      # not 9050: stays clear of a system-wide tor
TOR_CONTROL = 9251
FULCRUM_PORT = 50001
FULCRUM_STATS = 50081
MEMPOOL_PORT = 4080


def app_current(name: str) -> Path:
    return APPS_DIR / name / "current"


def ensure_dirs():
    for d in (CONFIG_DIR, DATA_DIR, APPS_DIR, DOWNLOADS_DIR, TOR_DIR, MEMPOOL_DIR):
        d.mkdir(parents=True, exist_ok=True)
    os.chmod(CONFIG_DIR, 0o700)
    os.chmod(TOR_DIR, 0o700)
