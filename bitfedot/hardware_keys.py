def _root_file(path: str, content: str, mode="644") -> str:
    """Shell lines writing `content` to a root-owned file (content is ours, never user input)."""
    marker = "BITFEDOT_FILE_EOF"
    assert marker not in content
    return (f"sudo install -d -m 755 {_q(os.path.dirname(path))}\n"
            f"sudo tee {_q(path)} >/dev/null <<'{marker}'\n{content.rstrip()}\n{marker}\n"
            f"sudo chmod {mode} {_q(path)}\n")


def _protect_packages() -> str:
    return (_root_file(PROTECTED, "# Installed by BitFedot: needed to unlock the disk and log in with a "
                                  "hardware key\n" + "\n".join(PROTECTED_PACKAGES))
            + f"sudo dnf mark user -y {' '.join(PACKAGES)} libfido2 >/dev/null 2>&1 || true\n")


