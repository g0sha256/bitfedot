# ------------------------------------------------------------------ facts --
def luks_devices() -> list:
    """Encrypted volumes that are unlocked at boot: [{'device', 'uuid', 'mapper'}]."""
    try:
        import json
        tree = json.loads(run(["lsblk", "-J", "-o", "PATH,TYPE,FSTYPE,UUID,NAME"], timeout=15).stdout)
    except ValueError:
        return []
    found = []

    def walk(nodes):
        for n in nodes:
            kids = n.get("children", [])
            if n.get("fstype") == "crypto_LUKS" and any(k.get("type") == "crypt" for k in kids):
                found.append({"device": n["path"], "uuid": n.get("uuid", ""),
                              "mapper": next(k["name"] for k in kids if k.get("type") == "crypt")})
            walk(kids)
    walk(tree.get("blockdevices", []))
    # First = the one named first on the kernel command line; it is the volume that
    # asks for PIN and touch at boot, the others follow it.
    try:
        cmdline = Path("/proc/cmdline").read_text()
    except OSError:
        cmdline = ""
    order = re.findall(r"rd\.luks\.uuid=(luks-[0-9a-f-]+)", cmdline)
    found.sort(key=lambda d: order.index(d["mapper"]) if d["mapper"] in order else len(order))
    return found


def yubikeys_present() -> int:
    """How many YubiKeys are plugged in, read from the USB device list only.

    This must NOT talk to the key: a second program opening the key resets its
    smart-card session, which aborts whatever is using it at that moment (for
    instance a script waiting for a PIN). Anything polled goes through here."""
    count = 0
    for vendor in Path("/sys/bus/usb/devices").glob("*/idVendor"):
        try:
            count += vendor.read_text().strip() == "1050"       # Yubico
        except OSError:
            pass
    return count


def plugged_serials() -> list:
    """Serial numbers of the plugged-in keys. Talks to the keys — call it only on
    an explicit user action, never from polling (see yubikeys_present)."""
    if not system.have("ykman"):
        return []
    return [s for s in run(["ykman", "list", "--serials"], timeout=15).stdout.split() if _SERIAL.match(s)]


def fido2_unlocked_this_boot() -> bool:
    """Did systemd unlock a volume with a FIDO2 token during this boot?"""
    out = run(["journalctl", "-b", "-o", "cat", "--no-pager", "-g", "fido2", "-t", "systemd-cryptsetup"],
              timeout=30).stdout.lower()
    return "fido2" in out and ("unlock" in out or "activat" in out or "authenticat" in out)


def missing_tools() -> list:
    """Fedora packages a step would still have to install (each step does so itself)."""
    libexec = run(["gpgconf", "--list-dirs", "libexecdir"], timeout=15).stdout.strip() or "/usr/libexec"
    checks = (("yubikey-manager", system.have("ykman")), ("pamu2fcfg", system.have("pamu2fcfg")),
              ("fido2-tools", system.have("fido2-token")),
              ("pam-u2f", any(os.path.exists(f"{d}/security/pam_u2f.so") for d in ("/usr/lib64", "/usr/lib"))),
              # gpgconf lists the component even when the program is absent: look for the file
              ("gnupg2-scdaemon", os.access(os.path.join(libexec, "scdaemon"), os.X_OK)))
    return [pkg for pkg, present in checks if not present]


def pgp_fingerprints() -> list:
    """Fingerprints of the signing key(s) created by the signing-key step."""
    try:
        return [f for f in (paths.CONFIG_DIR / "hwkey-pgp.fpr").read_text().split() if len(f) == 40]
    except OSError:
        return []


_keyring_facts = (0.0, {})


def keyring_facts() -> dict:
    """What the keyring step depends on; remembered for a minute, because the page polls.
      keyring_supported / keyring_reason: can this desktop open the keyring from a stored
          credential at all (keyring_unlock.supported())?
      keyring_encrypted: is the credential — or the key it is encrypted with — on an
          encrypted disk? If neither is, whoever holds the disk can read the keyring."""
    global _keyring_facts
    at, known = _keyring_facts
    if not known or time.monotonic() - at > 60:
        ok, reason = keyring_unlock.supported()
        known = {"keyring_supported": ok, "keyring_reason": reason,
                 "keyring_encrypted": (system.on_encrypted_volume(paths.CREDSTORE_DIR)
                                       or system.on_encrypted_volume("/var/lib/systemd"))}
        _keyring_facts = (time.monotonic(), known)
    return dict(known)


def hidden_at_login(user: str):
    """Does the login screen leave this user out of its list? It does for an account the
    accounts service calls locked, and then asks for a name to be typed instead.
    -> True | False, or None when the accounts service does not answer."""
    bus = ["busctl", "--system", "--no-pager"]
    found = run(bus + ["call", "org.freedesktop.Accounts", "/org/freedesktop/Accounts",
                       "org.freedesktop.Accounts", "FindUserByName", "s", user], timeout=15).stdout.split()
    if len(found) != 2 or found[0] != "o":
        return None
    said = run(bus + ["get-property", "org.freedesktop.Accounts", found[1].strip('"'),
                      "org.freedesktop.Accounts.User", "Locked"], timeout=15).stdout.split()
    return said[1] == "true" if len(said) == 2 and said[0] == "b" else None


def pam_wired() -> bool:
    """Do the login settings in force actually call the hardware-key module, and is it there?
    (The feature can be switched on while the generated file lacks it: a release upgrade
    may replace the profile it is generated from.)"""
    try:
        stack = Path(PAM_STACK).read_text()
    except OSError:
        return False
    return "pam_u2f.so" in stack and any(os.path.exists(m) for m in PAM_MODULES)


def facts() -> dict:
    """Everything about the system the stages depend on. Unprivileged, and safe
    to poll: it never opens a connection to a key."""
    user = os.environ.get("USER", "")
    auth = run(["authselect", "current"], timeout=15).stdout
    pw = run(["passwd", "-S", user], timeout=15).stdout.split()
    return {
        "user": user,
        "missing_tools": missing_tools(),
        "pgp": pgp_fingerprints(),
        "present": yubikeys_present(),
        "luks": luks_devices(),
        "fido2_boot": fido2_unlocked_this_boot(),
        "pam_u2f": "with-pam-u2f" in auth,
        "pam_wired": pam_wired(),
        "password_locked": len(pw) > 1 and pw[1].startswith("L"),
        "hidden_at_login": hidden_at_login(user) if _USER.match(user) else None,
        "terminal": terminal_command() is not None,
        **keyring_facts(),
    }


def state(s=None) -> dict:
    """Progress recorded in settings: {'main': serial, 'backup': serial,
    'boot_ok': [serials], 'login_ok': [serials], 'disk': bool, 'pgp': str, 'final': bool,
    'keyring': bool}"""
    hw = dict((s or settings.load()).get("hwkeys") or {})
    hw.setdefault("boot_ok", [])
    hw.setdefault("login_ok", [])
    return hw


def record(**changes) -> dict:
    hw = {**state(), **changes}
    settings.update(hwkeys=hw)
    return hw


def health(f: dict = None, hw: dict = None) -> list:
    """Problems that could stop a hardware key from working after an update.
    -> [(severity 'critical' | 'warning', message)]; empty when all is well."""
    f, hw = f or facts(), hw or state()
    problems = []
    if not any(hw.get(r) for r in ROLES):
        return problems
    for flag in sorted(Path(BOOT_FLAGS).glob("boot-warning-*")):
        kernel = flag.name[len("boot-warning-"):]
        if Path("/lib/modules", kernel).exists():           # ignore kernels that were removed since
            problems.append(("critical", f"The boot image of kernel {kernel} has no hardware-key support. "
                                         "Do not restart until this is fixed: run "
                                         f"“sudo dracut --force --kver {kernel}”."))
    if f["password_locked"] and not f["pam_u2f"]:
        problems.append(("critical", "Your password is locked but hardware-key login is switched off. "
                                     "Fix it before closing this session: "
                                     "“sudo authselect enable-feature with-pam-u2f”. " + REPAIR_HINT))
    elif f["pam_u2f"] and not f.get("pam_wired", True):
        problems.append(("critical" if f["password_locked"] else "warning",
                         "Hardware-key login is switched on, but the login settings in force do not use "
                         "it (an update may have replaced them). Do not log out or restart until this "
                         "is fixed. " + REPAIR_HINT))
    if f["password_locked"] and f.get("hidden_at_login"):
        problems.append(("warning", "The login screen does not list you and asks for your user name "
                                    "instead: the account counts as locked. Logging in with the key "
                                    "still works. " + REPAIR_HINT))
    if (hw.get("disk") or f["pam_u2f"]) and not os.path.exists(PROTECTED):
        problems.append(("warning", "The packages needed for hardware-key boot and login are not "
                                    "protected from removal. Run the disk and login steps again."))
    return problems


